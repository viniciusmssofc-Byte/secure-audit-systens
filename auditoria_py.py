    {"id": 3, "nome": "Marcos Lima", "setor": "Finanças", "valor": 12500.00},  # Valor suspeito/alto
    {"id": 4, "nome": "Julia Costa", "setor": "TI", "valor": -500.00},        # Erro de digitação/fraude
