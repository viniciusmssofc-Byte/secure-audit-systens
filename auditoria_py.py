def analisar_dados(lista_transacoes):
    print("=== INICIANDO AUDITORIA DE SEGURANÇA E DADOS ===")

    total_gasto = 0
    alertas_seguranca = []

    for t in lista_transacoes:
        total_gasto += t["valor"]

        # Regra de Auditoria 1: Valores negativos não deveriam existir num pagamento direto
        if t["valor"] < 0:
            alertas_seguranca.append(f"ALERTA DE SEGURANÇA: Usuário {t['nome']} (ID: {t['id']}) possui valor negativo: R${t['valor']}")

        # Regra de Auditoria 2: Alerta de teto salarial ou auditoria para valores muito altos
        if t["valor"] > 10000:
            alertas_seguranca.append(f"AUDITORIA NECESSÁRIA: Usuário {t['nome']} (ID: {t['id']}) possui valor acima do limite operacional: R${t['valor']}")

    # 3. Exibindo os resultados no terminal
    print(f"\nTotal processado na folha: R$ {total_gasto:.2f}")
    print(f"Total de registros analisados: {len(lista_transacoes)}")

    print("\n--- Relatório de Riscos / Vulnerabilidades ---")
    if alertas_seguranca:
        for alerta in alertas_seguranca:
            print(alerta)
    else:
        print("Nenhuma inconsistência encontrada.")

# Executar a função
