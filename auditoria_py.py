import pandas as pd

# 1. Banco de dados inicial dos Setores (Nome do Setor: Valor Fixo/Teto Salarial)
# Aqui gerenciamos as regras de negócio de cada setor
tabela_setores = {
    "TI": 5000.00,
    "Operacoes": 3500.00,
    "Financas": 12000.00,
    "Seguranca": 6000.00
}

# --- FUNÇÕES DE GERENCIAMENTO DE SETORES (CRUD) ---

def criar_setor(nome, valor_fixo):
    tabela_setores[nome] = float(valor_fixo)
    print(f"✅ Setor '{nome}' criado com sucesso! Valor fixo: R$ {valor_fixo:.2f}")

def editar_setor(nome, novo_valor):
    if nome in tabela_setores:
        tabela_setores[nome] = float(novo_valor)
        print(f"🔄 Setor '{nome}' atualizado para o valor: R$ {novo_valor:.2f}")
    else:
        print(f"❌ Erro: Setor '{nome}' não encontrado.")

def excluir_setor(nome):
    if nome in tabela_setores:
        del tabela_setores[nome]
        print(f"🗑️ Setor '{nome}' foi excluído do sistema.")
    else:
        print(f"❌ Erro: Setor '{nome}' não encontrado.")

# --- FUNÇÃO PRINCIPAL DE AUDITORIA E LEITURA DE CSV ---

def executar_auditoria(caminho_csv):
    print("\n" + "="*20 + " INICIANDO AUDITORIA COM PANDAS " + "="*20)

    # Lendo o arquivo CSV real
    try:
        df = pd.read_csv(caminho_csv)
    except FileNotFoundError:
        print(f"❌ Arquivo '{caminho_csv}' não encontrado. Crie o arquivo na pasta lateral primeiro.")
        return

    alertas = []
    total_orcamento_projetado = 0

    print("\n📋 Registros lidos do arquivo:")
    # Passando por cada linha do arquivo CSV
    for index, linha in df.iterrows():
        nr_cadastro = linha['Nr Cadastro']
        nome = linha['Nome']
        setor = linha['Setor']

        # Cruzando dados: Verifica se o setor existe nas nossas regras
        if setor in tabela_setores:
            valor_setor = tabela_setores[setor]
            total_orcamento_projetado += valor_setor
            print(f"ID {nr_cadastro} | {nome:<18} | Setor: {setor:<10} | Valor Alocado: R$ {valor_setor:.2f}")
        else:
            # Alerta de segurança: Funcionário alocado em um setor inválido ou excluído!
            alertas.append(f"⚠️ ALERTA DE RISCO: Funcionário {nome} (Nr Cadastro: {nr_cadastro}) está listado no setor inválido/inexistente '{setor}'!")

    # Exibindo o resumo consolidado
    print("\n" + "-"*50)
    print(f"💰 Custo Total Projetado (Setores Ativos): R$ {total_orcamento_projetado:.2f}")
    print(f"📊 Total de funcionários auditados: {len(df)}")
    print("-"*50)

    # Exibindo alertas se houverem inconsistências
    if alertas:
        print("\n🚨 RELATÓRIO DE INCONSISTÊNCIAS DETECTADAS:")
        for alerta in alertas:
            print(alerta)
    else:
        print("\n🔒 Auditoria Concluída: 100% de conformidade com os setores ativos.")


